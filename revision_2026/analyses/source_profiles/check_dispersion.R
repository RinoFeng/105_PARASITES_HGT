args <- commandArgs(trailingOnly=TRUE)
root <- if(length(args)) args[[1]] else 'analysis/revision_pnas/revision_round2_assessment/manuscript_evidence_completion_20261003'
library(vegan)
x <- read.delim(file.path(root,'data/dispersion_phylum_counts.tsv'),check.names=FALSE,row.names=1)
m <- read.delim(file.path(root,'data/dispersion_metadata.tsv'),stringsAsFactors=FALSE)
m <- m[match(rownames(x),m$Specie),];stopifnot(all(rownames(x)==m$Specie),all(rowSums(x)>0))
m$Niche <- factor(m$Niche)
d <- vegdist(decostand(x,'total'),method='bray')
write_tsv <- function(x,n) write.table(x,file.path(root,'data',n),sep='\t',quote=FALSE,row.names=FALSE,na='NA')
set.seed(20261003)
a <- adonis2(d ~ Niche,data=m,permutations=999)
write_tsv(data.frame(term=rownames(a),a,check.names=FALSE),'source_permanova_reproduced.tsv')
settings <- data.frame(version=c('primary_median_bias_adjusted','median_unadjusted','median_bias_adjusted_Lingoes'),bias=c(TRUE,FALSE,TRUE),add=c('FALSE','FALSE','lingoes'))
results <- list();observations <- list();groups <- list()
for(i in seq_len(nrow(settings))){
 cfg <- settings[i,];warnings <- character()
 b <- withCallingHandlers(betadisper(d,m$Niche,type='median',bias.adjust=cfg$bias,add=if(cfg$add=='FALSE') FALSE else 'lingoes'),warning=function(w){warnings<<-c(warnings,conditionMessage(w));invokeRestart('muffleWarning')})
 set.seed(20261003);p <- permutest(b,permutations=9999)
 results[[i]] <- data.frame(version=cfg$version,n=nrow(x),groups=nlevels(m$Niche),F=p$tab[1,'F'],df_group=p$tab[1,'Df'],df_residual=p$tab[2,'Df'],P=p$tab[1,'Pr(>F)'],permutations=9999,seed=20261003,type='median',bias_adjust=cfg$bias,add=cfg$add,negative_eigenvalues=sum(b$eig < -1e-10),warnings=paste(unique(warnings),collapse=' | '))
 observations[[i]] <- data.frame(version=cfg$version,species=m$Specie,group=m$Niche,distance=as.numeric(b$distances))
 groups[[i]] <- do.call(rbind,lapply(levels(m$Niche),function(g){z=b$distances[m$Niche==g];data.frame(version=cfg$version,group=g,n=length(z),mean_distance=mean(z),median_distance=median(z),sd_distance=sd(z))}))
}
write_tsv(do.call(rbind,results),'dispersion_tests.tsv');write_tsv(do.call(rbind,observations),'dispersion_species_distances.tsv');write_tsv(do.call(rbind,groups),'dispersion_group_summary.tsv')
write_tsv(data.frame(software=c('R','vegan','permute'),version=c(as.character(getRversion()),as.character(packageVersion('vegan')),as.character(packageVersion('permute')))),'dispersion_software_versions.tsv')
print(a);print(do.call(rbind,results));print(table(m$Niche))
